export function resolveLocationFromText(text) {
  if (!text) return INDIAN_LOCATIONS[0];

  const lower = text.toLowerCase();

  // 1. Check direct multi-lingual and alias mapping
  for (const item of LOCATION_ALIASES) {
    if (item.keywords.some(k => lower.includes(k.toLowerCase()))) {
      return item.location;
    }
  }

  // 2. Check INDIAN_LOCATIONS table
  for (const loc of INDIAN_LOCATIONS) {
    if (
      lower.includes(loc.landmark.toLowerCase()) ||
      lower.includes(loc.city.toLowerCase()) ||
      lower.includes(loc.district.toLowerCase()) ||
      lower.includes(loc.state.toLowerCase())
    ) {
      return loc;
    }
  }

  // 3. Fallback to random realistic location or default
  return INDIAN_LOCATIONS[Math.floor(Math.random() * INDIAN_LOCATIONS.length)];
}
